def eq(name, lhs, rhs):
    ok = (lhs == rhs)
    print(f"{'PASS' if ok else 'FAIL'}  {name}: {lhs} == {rhs}")
    if not ok: fails.append(name)
def pct(name, num, den, expect):
    v = round(num / den * 100, 1)
    ok = (v == expect)
    print(f"{'PASS' if ok else 'FAIL'}  {name}: {num}/{den} = {v}% (expect {expect}%)")
    if not ok: fails.append(name)
def fps(name, gap, expect):
    v = round(1e9 / gap, 1)
    ok = (v == expect)
    print(f"{'PASS' if ok else 'FAIL'}  {name}: 1e9/{gap} = {v} (expect {expect})")
    if not ok: fails.append(name)

