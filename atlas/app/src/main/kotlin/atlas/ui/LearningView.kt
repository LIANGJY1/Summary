                                },
                                onDrag = { change, dragAmount ->
                                    change.consume()
                                    // 增量累计指针位置（卡片自身平移后 change.position 坐标系会漂移）
                                    dragPointerY += dragAmount.y
                                    val key = draggingKey ?: return@detectDragGestures
                                    val base = store.sourceQuestions
                                    val from = base.indexOfFirst { sourceQuestionKey(it) == key }
                                    if (from < 0) return@detectDragGestures
                                    val current = dragTargetIndex ?: from
                                    val draggedTop = cardTops[key] ?: return@detectDragGestures
                                    val order = base.toMutableList().apply { add(current, removeAt(from)) }
                                    fun pitch(k: String) = (cardHeights[k] ?: 96) + rowSpacingPx
                                    val grabY = dragPointerY - dragGrabOffset
                                    var target = current
                                    var top = draggedTop
                                    var guard = 0
                                    // 启动器算法：视觉位置越过「当前槽位与相邻槽位顶点连线的中点」就换位。上下行的换位线都必须
                                    // 按「被越过那行」的行距推导，再加半行距滞回：行高不均时若下行用自身行距，换位线两侧不对称，
                                    // 会提前连环换位、下一帧又弹回，表现为列表乱跳。
                                    val hysteresis = rowSpacingPx / 2
                                    while (guard++ < 64) {
                                        val nextPitch = if (target < order.lastIndex) pitch(sourceQuestionKey(order[target + 1])) else 0f
                                        val prevPitch = if (target > 0) pitch(sourceQuestionKey(order[target - 1])) else 0f
                                        when {
                                            target < order.lastIndex && grabY > top + nextPitch / 2 + hysteresis -> {
                                                top += nextPitch
                                                order.add(target + 1, order.removeAt(target))
                                                target++
                                            }
                                            target > 0 && grabY < top - prevPitch / 2 - hysteresis -> {
                                                top -= prevPitch
                                                order.add(target - 1, order.removeAt(target))
                                                target--
                                            }
                                            else -> break
                                        }
                                    }
                                    if (target != current) dragTargetIndex = target
                                },
                            )
                        },
                ) {
                    Row(
                        Modifier.fillMaxWidth(),
                        verticalAlignment = Alignment.Top,
                    ) {
                        if (reorderMode) {
                            Surface(
                                color = if (isDragging) Theme.Accent.copy(alpha = 0.22f) else Theme.Accent.copy(alpha = 0.10f),
                                shape = MaterialTheme.shapes.small,
                            ) {
                                Text(
                                    "${displayIndex + 1}",
                                    Modifier.padding(horizontal = 7.dp, vertical = 3.dp),
                                    color = Theme.Accent,
                                    fontWeight = FontWeight.Bold,
                                    fontSize = 12.sp,
                                )
                            }
                            Spacer(Modifier.width(8.dp))
                        }
                        Column(
                            Modifier.weight(1f).singleClickWithoutConsumingSelection {
                                if (reorderMode) return@singleClickWithoutConsumingSelection
                                locateSource(entry.sourcePath)
                                expanded = if (isExpanded) expanded - entryKey else expanded + entryKey
                            },
                        ) {
                            Text("Q${entry.number}", fontSize = 11.sp, color = Theme.Muted)
                            Spacer(Modifier.height(2.dp))
                            SelectionContainer {
                                Text(entry.question, style = ui.typography.itemTitle)
                            }
                            if (searchScope == QuestionSearchScope.ALL && query.isNotBlank()) {
                                Text(entry.sourcePath, fontSize = 10.sp, color = Theme.Accent, maxLines = 1)
                            }
                        }
                    }
                    // 展开/收起必须带高度动画：直接增删答案块会让卡片高度瞬间跳变，下方卡片只能靠弹簧
                    // 滑过来补位，过渡期盖在答案上互相重叠。高度连续变化后，跟随卡片才能同步滑动不脱节。
                    // 弹簧参数与让位卡片一致，卡片底边与下方卡片作为一个系统运动；从顶部展开对齐题干。
                    AnimatedVisibility(
                        visible = isExpanded,
                        enter = expandVertically(
                            spring(
                                dampingRatio = Spring.DampingRatioLowBouncy,
                                stiffness = Spring.StiffnessMedium,
                                visibilityThreshold = IntSize.VisibilityThreshold,
                            ),
                            expandFrom = Alignment.Top,
                        ) + fadeIn(tween(120)),
                        exit = shrinkVertically(
                            spring(
                                dampingRatio = Spring.DampingRatioLowBouncy,
                                stiffness = Spring.StiffnessMedium,
                                visibilityThreshold = IntSize.VisibilityThreshold,
                            ),
                            shrinkTowards = Alignment.Top,
                        ) + fadeOut(tween(90)),
                    ) {
                        Column {
                            Spacer(Modifier.height(10.dp))
                            if (entry.answer.isBlank()) {
                                Text("暂无答案", fontSize = 12.sp, color = Theme.WarnOrange)
                            } else {
                                Surface(
                                    modifier = Modifier
                                        .fillMaxWidth()
                                        .singleClickWithoutConsumingSelection {
                                            if (store.settings.clickAnswerToEdit) editingEntry = entry
                                        },
                                    shape = MaterialTheme.shapes.small,
                                    color = if (store.settings.markdownStyle == "classic") {
                                        Theme.OkGreen.copy(alpha = 0.10f)
                                    } else {
                                        MaterialTheme.colorScheme.surfaceVariant.copy(alpha = 0.55f)
