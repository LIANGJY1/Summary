#!/usr/bin/env bash
# scaffold.sh <目标目录> <特性名> —— 生成 srs-driven-dev 工作区骨架
# 用法示例：bash scaffold.sh ~/Project/MyProject/Summary/project/x/dclock 车模
set -euo pipefail
DIR="${1:?用法: scaffold.sh <目标目录> <特性名>}"
NAME="${2:?用法: scaffold.sh <目标目录> <特性名>}"

if [ -e "$DIR" ] && [ -n "$(ls -A "$DIR" 2>/dev/null)" ]; then
  echo "目标目录非空，不覆盖：$DIR" >&2; exit 1
fi
mkdir -p "$DIR"

write() { # $1 文件名 $2 内容
  cat > "$DIR/$1"
}

write "README.md" <<EOF
# ${NAME} — 需求与设计工作区

## 文档职责（单一事实源，禁止跨文档重复定义）

| 文件 | 唯一职责 |
|---|---|
| 01-需求规格.md | 事实 F／决策 D／全局规则 G／术语／接口清单／条目目录 |
| 02-规则矩阵.md | 冲突/竞合规则唯一权威（未定稿则文头标"整体 TBD"） |
| 03-条目档案.md | 每条需求：状态＋事实＋QA 问答＋开放点；文末跨条目开放点 |
| 04-代码方案.md | 分层架构＋不确定点隔离表＋落地阶段 |

## 维护规则

1. 每类内容只在一处定义，他处只引用编号。
2. 新需求条目追加进 03；F/D/G 变更进 01；编号单调递增不复用。
3. 所有讨论结论必须落盘。
EOF

write "01-需求规格.md" <<EOF
# ${NAME} 需求规格

> 版本：v0.1　　日期：$(date +%F)
> 文档职责见 README；本文只定义，不复述他处内容。

## 1. 概述

（一段话：是什么、谁渲染/谁集成、职责红线）

## 2. 既定事实（F）

| # | 事实 | 来源 |
|---|---|---|

## 3. 决策记录（D）

## 4. 全局规则（G）

| # | 规则 |
|---|---|

## 5. 术语表

## 6. 条目索引（结论以 03 为准）

| 条目 | 主题 |
|---|---|

## 7. 信号与接口清单

## 附录 — 讨论日志
EOF

write "02-规则矩阵.md" <<EOF
# ${NAME} 规则矩阵

> **状态：整体 TBD（未定稿前标注）**。规则唯一权威出处＝本文件，他处只引用。
> 方向约定：行＝当前状态，列＝新触发，单元格＝处理规则。

（矩阵定稿后填入；未定稿前可先放讨论稿并注明）
EOF

write "03-条目档案.md" <<EOF
# 需求条目档案

> 每条目格式：状态行（✅/🔶＋日期＋开放点索引）→ 事实（2~4 行，挂 F 编号）→
> 问答（有序列表，答案另起一行以 QA: 开头）→ 开放点（TBD/TD/DEP 挂本条目，已解决划线留痕）。
> 原文表格不保留，其信息全部并入事实与问答。新条目追加于末尾。

---

# 跨条目开放点

> 仅收录不属于单一需求 ID 的悬置项。
EOF

write "04-代码方案.md" <<EOF
# ${NAME} 全局代码方案

> 版本：v0.1　　日期：$(date +%F)
> 骨架：三层架构（信号源/核心/执行）＋不确定点隔离表＋落地阶段表。

## 1. 设计原则

## 2. 总体架构

## 3. 包结构与类职责

## 4. 事件与核心流转

## 5. 不确定点隔离表（TBD/TD/DEP ↔ 唯一代码落点）

| 编号 | 不确定点 | 代码落点 | 现行策略 |
|---|---|---|---|

## 6. 与既有代码的关系

## 7. 落地顺序（每阶段＝一次可验证交付）

| 阶段 | 范围 | 确定度 | 验收标准 | 前置 |
|---|---|---|---|---|

## 8. 变更管理

需求变动 → 先改 03（必要时 01）→ 代码只动对应 Source/Config/规则行 → 开放点同步。
EOF

echo "工作区已创建：$DIR"
ls -1 "$DIR"
